-- Synthetic demo schema. Oracle Database 12c+; run in a disposable lab schema.
-- Object names are intentionally fictional and avoid proprietary schemas.
CREATE TABLE demo_customers (
    customer_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    display_name NVARCHAR2(120) NOT NULL,
    segment NVARCHAR2(30) NOT NULL
);

CREATE TABLE demo_orders (
    order_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    customer_id NUMBER(10) NOT NULL REFERENCES demo_customers(customer_id),
    created_at TIMESTAMP(0) NOT NULL,
    status VARCHAR2(12) NOT NULL CHECK (status IN ('COMPLETED', 'VOID')),
    amount NUMBER(18,2) NOT NULL CHECK (amount >= 0)
);

-- Unlike SQL Server, Oracle does not support INCLUDE columns in B-tree indexes.
-- Revisit the column order/size based on measured workload and optimizer plans.
CREATE INDEX ix_demo_orders_period
    ON demo_orders(created_at, status, customer_id);
